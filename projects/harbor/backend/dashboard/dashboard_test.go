func TestCheck(t *testing.T) {
	for _, tc := range []struct {
		name, source string
		// want is exact, except that one ending in "..." is a prefix, and
		// more problems may follow it.
		want []string
	}{
		{"passes a dashboard that compiles", good, nil},
		{"needs a template", "<script setup>\nconst a = 1\n</script>\n", []string{"a dashboard needs a <template>"}},
		{"allows only vue and harbor", strings.Replace(good, `"harbor"`, `"lodash"`, 1),
			[]string{`a dashboard can only import from "vue" and "harbor", not "lodash"`}},
		{"allows only vue and harbor in a plain script", "<script>\nimport _ from \"lodash\"\nexport default { data: () => ({ n: _.x }) }\n</script>\n<template><p/></template>\n",
			[]string{`a dashboard can only import from "vue" and "harbor", not "lodash"`}},
		{"says what harbor has instead of what it lacks", strings.Replace(good, `import { format } from "harbor"`, `import { format, Inbox } from "harbor"`, 1),
			[]string{`"harbor" has no Inbox. Did you mean InboxWidget? search_kit finds what it has.`}},
		{"says where to look when nothing is close", strings.Replace(good, `import { format } from "harbor"`, `import { format, Spreadsheet } from "harbor"`, 1),
			[]string{`"harbor" has no Spreadsheet. search_kit finds what it has.`}},
		{"reports script errors with the file's line", strings.Replace(good, "ref<number>(0)", "ref<number>(0", 1),
			[]string{`line 5: Unexpected token, expected ","`}},
		{"reports template errors with the file's line", strings.Replace(good, `<p @click="n++">{{ n }}</p>`, `<p>{{ n </p>`, 1),
			[]string{"line 8: ..."}},
		{"reports a broken file", `<template><p></template>`, []string{"line 1: ..."}},
		{"needs a service's name in quotes", "<script setup>\nimport { useService } from \"harbor\"\nconst name = \"a\"\nconst s = useService(name)\n</script>\n<template><p/></template>\n",
			[]string{`line 4: useService takes the service's name in quotes, such as useService("tasklane")`}},
		{"needs the service named", "<script setup>\nimport { useService } from \"harbor\"\nconst { list } = useService(\"a\")\n</script>\n<template><p/></template>\n",
			[]string{`line 3: name the service, as const a = useService("a"), and call its tools as a.tool_name(...)`}},
		{"needs each tool by name", "<script setup>\nimport { useService } from \"harbor\"\nconst a = useService(\"a\")\nconst tool = \"b\"\nconst f = a[tool]\n</script>\n<template><p/></template>\n",
			[]string{`line 5: call a's tools by name, as a.tool_name(...), so Harbor knows which tools the dashboard uses`}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := Check(tc.source)
			more := len(tc.want) > 0 && strings.HasSuffix(tc.want[len(tc.want)-1], "...")
			if len(got) < len(tc.want) || !more && len(got) != len(tc.want) {
				t.Fatalf("got %q, want %q", got, tc.want)
			}
			for i, w := range tc.want {
				if prefix, ok := strings.CutSuffix(w, "..."); ok {
					if !strings.HasPrefix(got[i], prefix) {
						t.Errorf("got %q, want it to start with %q", got[i], prefix)
					}
				} else if got[i] != w {
					t.Errorf("got %q, want %q", got[i], w)
				}
			}
		})
	}
}

// The dev fixtures' dashboards as they are now, which
// database/dev/017_catalog_dashboards.sql sets. The ones the migrations
// before it set are history.
func TestFixtureDashboardsCompile(t *testing.T) {
	files, _ := filepath.Glob("../../database/dev/assets/dashboards/catalog/*.vue")
	if len(files) == 0 {
		t.Fatal("no fixture dashboards")
	}
	for _, f := range files {
		source, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		if problems := Check(string(source)); problems != nil {
			t.Errorf("%s: %q", filepath.Base(f), problems)
		}
	}
}

// "harbor" is the kit's functions and its components, so the functions the
// backend knows must be the ones the frontend's harbor() gives, besides the
// Bound the compiler puts each widget in.
func TestHarborHasWhatTheFrontendGives(t *testing.T) {
	front, err := os.ReadFile("../../frontend/src/dashboards.ts")
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`module: \{ ([^}]*), \.\.\.kit \}`).FindSubmatch(front)
	if m == nil {
		t.Fatal("dashboards.ts: harbor() has no module: { ..., ...kit }")
	}
	var gives []string
	for _, f := range strings.Split(string(m[1]), ", ") {
		if name, _, _ := strings.Cut(f, ":"); name != "Bound" {
			gives = append(gives, name)
		}
	}
	if strings.Join(gives, ", ") != strings.Join(kit.Functions, ", ") {
		t.Errorf("harbor() gives %s; kit.Functions is %s", gives, kit.Functions)
	}
}

// The compiler finds the tools a dashboard uses, without running it, and
// puts each widget in a Bound that knows the tools behind its props and
// events.
func TestCompileFindsTheToolsEachWidgetUses(t *testing.T) {
	c, err := Compile(`<script setup>
import { computed, ref } from "vue"
import { useService, BoardWidget, Grid, Widget } from "harbor"
const tasklane = useService("tasklane")
const huddle = useService("huddle")
const mine = ref(true)
const issues = computed(() => tasklane.list_issues({ mine: mine.value }).issues)
const cards = computed(() => issues.value.map((i) => ({ title: i.title, column: i.state })))
const unused = computed(() => huddle.list_mentions())
</script>
<template>
  <Grid>
    <BoardWidget v-if="mine" title="Issues" :cards="cards" :columns="[]" @move="(c, s) => tasklane.update_issue({ key: c.key, state: s })" />
    <Widget :title="'Plain'"><p>{{ huddle.search_messages({ query: 'x' }).results.length }}</p></Widget>
  </Grid>
</template>
`)
	if err != nil {
		t.Fatal(err)
	}
	var uses []string
	for _, u := range c.Uses {
		uses = append(uses, u.Service+"."+u.Tool)
	}
	if got, want := strings.Join(uses, " "), "huddle.list_mentions huddle.search_messages tasklane.list_issues tasklane.update_issue"; got != want {
		t.Errorf("uses %s, want %s", got, want)
	}
	for _, want := range []string{
		`uses: [["tasklane", "list_issues"], ["tasklane", "update_issue"]]`,
		`uses: [["huddle", "search_messages"]]`,
		`"frame-title": () => "Issues"`,
		`"frame-title": () => "Plain"`,
	} {
		if !strings.Contains(c.JS, want) {
			t.Errorf("the module has no %s:\n%s", want, c.JS)
		}
	}
	// The v-if moved to the Bound: the widget is there or not, Bound and all.
	if !regexp.MustCompile(`\$setup\.mine \? [^\n]*createBlock\)\(_component_HarborBound`).MatchString(c.JS) {
		t.Errorf("the v-if is not on the Bound:\n%s", c.JS)
	}
}
